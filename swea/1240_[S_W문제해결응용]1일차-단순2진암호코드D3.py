def find_start_pos(cur_list, M):
    for idx in range(M - 1, -1, -1):
        if cur_list[idx] == "1":
            return idx - 55
    return -1


def is_ok(code):
    even = 0
    odd = 0
    for i in range(8):
        if i % 2 == 1:
            even += int(code[i])
        else:
            odd += int(code[i])
    if (odd * 3 + even) % 10 == 0:
        return True
    else:
        return False


