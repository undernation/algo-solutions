dydx = [[0, 1], [1, 0], [0, -1], [-1, 0]]


def bfs(start_id, target_ids):
    visited = set()
    sx, sy, cur_dir = gate_dict[start_id]
    targets = dict()
    # print(target_ids)
    for target_id in target_ids:
        tx, ty, target_dir = gate_dict[target_id]
        targets[(tx, ty, target_dir)] = target_id

    # print(sx, sy, tx, ty)
    cnt = 2
    q = deque()

    q.append((sx, sy, cur_dir, cnt))
    while q:
        cx, cy, cd, cur_cnt = q.popleft()

        dy, dx = dydx[cd]
        ny = cy + dy
        nx = cx + dx
        new_cnt = cur_cnt + 1
        # print("debug cx, cy, cd, cnt", cx, cy, cd, cur_cnt)
        # visited 처리 확인.

        # 도착했는지 확인
        if (cx, cy, cd) in targets:
            target_id = targets[(cx, cy, cd)]
            take_time[(start_id, target_id)] = cur_cnt

        # 교차로인지 확인,
        if (nx, ny) in cross_roads:
            # 교차로면 현재 켜져있는 방향으로 방향 수정 가능.
            for i in range(4):
                if board[ny][nx] & (1 << i):
                    new_dir = i
                    # visited 처리
                    # print("debug new_dir", new_dir)
                    if (nx, ny, i) in visited:
                        continue
                    visited.add((nx, ny, new_dir))
                    q.append((nx, ny, new_dir, new_cnt))

        # 교차로 아니면 그냥 그대로 진행.
        else:
            if (nx, ny, cd) in visited:
                continue
            visited.add((nx, ny, cd))
            q.append((nx, ny, cd, new_cnt))


