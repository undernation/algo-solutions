from collections import deque
from itertools import permutations

EAST = 0
SOUTH = 1
WEST = 2
NORTH = 3


def init(N):
    global g_N, board, cross_roads, gate_dict, take_time
    g_N = N
    board = [[0] * N for _ in range(N)]
    cross_roads = set()
    gate_dict = {}
    take_time = {}
    pass


def make_road(sx, sy, w, h):
    start_x = sx - 1
    end_x = sx + w
    start_y = sy - 1
    end_y = sy + h

    # 위쪽 테두리
    y = start_y
    for x in range(start_x, end_x):
        board[y][x] |= (1 << EAST)

    # 오른쪽 테두리
    x = end_x
    for y in range(start_y, end_y):
        board[y][x] |= (1 << SOUTH)

    # 아래쪽 테두리
    y = end_y
    for x in range(start_x + 1, end_x + 1):
        board[y][x] |= (1 << WEST)

    x = start_x
    for y in range(start_y + 1, end_y + 1):
        board[y][x] |= (1 << NORTH)

    take_time.clear()


def make_crossroads(sx, sy, w, h):
    start_x = sx - 1
    end_x = sx + w
    start_y = sy - 1
    end_y = sy + h
    cross_roads.add((start_x, start_y))
    cross_roads.add((end_x, start_y))
    cross_roads.add((start_x, end_y))
    cross_roads.add((end_x, end_y))


def make_gate(cur_id, sx, sy, w, h, doorx, doory):
    start_x = sx - 1
    end_x = sx + w
    start_y = sy - 1
    end_y = sy + h
    # 윗변에 있는지 확인
    if doory == 0:
        gate_dict[cur_id] = (start_x + doorx + 1, start_y, EAST)
    elif doory == h - 1:
        gate_dict[cur_id] = (start_x + doorx + 1, end_y, WEST)
    elif doorx == 0:
        gate_dict[cur_id] = (start_x, start_y + doory + 1, NORTH)
    elif doorx == w - 1:
        gate_dict[cur_id] = (end_x, start_y + doory + 1, SOUTH)


