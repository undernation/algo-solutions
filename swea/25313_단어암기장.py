g_N = 0
g_M = 0

rows = []
word_info = []

tree = []


def init(N: int, M: int) -> None:
    global g_N, g_M
    global rows, word_info, tree

    g_N = N
    g_M = M

    rows = [[] for _ in range(N)]

    # word_info[mID] = (row, start, length)

    word_info = [None] * 55001

    tree = [0] * (4 * N)

    build(0, N - 1, 1)


def build(s, e, node):
    if s == e:
        tree[node] = g_M
        return

    mid = (s + e) // 2

    build(s, mid, node * 2)
    build(mid + 1, e, node * 2 + 1)

    tree[node] = max(
        tree[node * 2],
        tree[node * 2 + 1]
    )


def update(s, e, node, target, value):
    if s == e:
        tree[node] = value
        return
    mid = (s + e) // 2

    if target <= mid:
        update(
            s,
            mid,
            node * 2,
            target,
            value
        )
    else:
        update(
            mid + 1,
            e,
            node * 2 + 1,
            target,
            value
        )
    tree[node] = max(
        tree[node * 2],
        tree[node * 2 + 1]
    )


def find_first(s, e, node, mLen):
    if tree[node] < mLen:
        return -1

    if s == e:
        return s

    mid = (s + e) // 2
    left = node * 2
    right = node * 2 + 1

    if tree[left] >= mLen:
        return find_first(s, mid, left, mLen)

    return find_first(mid + 1, e, right, mLen)


def get_max_gap(row):
    max_gap = 0
    prev_end = 0

    for start, length, word_id in rows[row]:
        gap = start - prev_end
        max_gap = max(max_gap, gap)

        prev_end = start + length
    max_gap = max(
        max_gap,
        g_M - prev_end
    )

    return max_gap


def writeWord(mId: int, mLen: int) -> int:
    row = find_first(
        0,
        g_N - 1,
        1,
        mLen
    )

    if row == -1:
        return -1

    words = rows[row]

    prev_end = 0
    start = -1
    insert_idx = len(words)

    for i in range(len(words)):
        cur_start, cur_len, cur_id = words[i]
        gap = cur_start - prev_end

        if gap >= mLen:
            start = prev_end
            insert_idx = i
            break
        prev_end = cur_start + cur_len

    if start == -1:
        start = prev_end

    words.insert(
        insert_idx,
        (start, mLen, mId)
    )

    word_info[mId] = (
        row,
        start,
        mLen
    )

    max_gap = get_max_gap(row)

    update(
        0,
        g_N - 1,
        1,
        row,
        max_gap
    )

