def dfs(r, c, size, s):
    global idx

    if s[idx] == "0" or s[idx] == "1":
        value = int(s[idx])
        idx += 1

        for i in range(r, r + size):
            for j in range(c, c + size):
                board[i][j] = value

        return

    idx += 1
    half = size // 2

    dfs(r, c, half, s)
    dfs(r, c + half, half, s)
    dfs(r + half, c, half, s)
    dfs(r + half, c + half, half, s)

    idx += 1


