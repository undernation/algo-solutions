def encode_dfs(r, c, size):
    global encode_length
    ret = ""

    if check_same(r, c, size, board[r][c]):
        encode_length += 1
        return str(board[r][c])

    half = size // 2
    ret += "("
    encode_length += 1

    ret += encode_dfs(r, c, half)
    ret += encode_dfs(r, c + half, half)
    ret += encode_dfs(r + half, c, half)
    ret += encode_dfs(r + half, c + half, half)

    encode_length += 1
    ret += ")"

    return ret


