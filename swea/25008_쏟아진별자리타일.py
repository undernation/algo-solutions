def make_code(cur_board):
    ret = ""

    for i in range(5):
        for j in range(5):
            ret += str(cur_board[i][j])
    return ret

def rotate(cur_board):
    new_board = [[0] * 5 for _ in range(5)]

    for i in range(5):
        for j in range(5):
            new_board[i][j] = cur_board[j][4 - i]
    return new_board

