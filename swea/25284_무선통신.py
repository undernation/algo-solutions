from typing import List
import heapq


SEC_SIZE = 100
MAX_ID = 50000


g_N = 0
g_limit = 0
section_cnt = 0
limit_sec = 0

# section -> 모든 radio ID
board = []

# freq -> {section_index: [radio IDs]}
specific_board = {}

# ID 최대 50,000 이므로 dict/object 대신 배열로 바로 접근
radio_freq = []
radio_y = []
radio_x = []


def init(N: int, mLimit: int) -> None:
    global g_N, g_limit
    global section_cnt, limit_sec
    global board, specific_board
    global radio_freq, radio_y, radio_x

    g_N = N
    g_limit = mLimit

    # 좌표 100칸 = power 1000
    #
    # same frequency 최대거리:
    # mLimit / 10
    #
    # 이를 section으로 바꾸면:
    # mLimit / 10 / 100
    # = mLimit / 1000
    limit_sec = mLimit // 1000

    section_cnt = (N + SEC_SIZE - 1) // SEC_SIZE

    # section은 최대
    # 100 x 100 = 10,000개
    board = [
        []
        for _ in range(section_cnt * section_cnt)
    ]

    # freq -> {section: [IDs]}
    specific_board = {}

    radio_freq = [0] * (MAX_ID + 1)
    radio_y = [0] * (MAX_ID + 1)
    radio_x = [0] * (MAX_ID + 1)


def addRadio(
    K: int,
    mID: List[int],
    mFreq: List[int],
    mY: List[int],
    mX: List[int]
) -> None:

    for i in range(K):
        rid = mID[i]
        freq = mFreq[i]
        y = mY[i]
        x = mX[i]

        sy = y // SEC_SIZE
        sx = x // SEC_SIZE

        sec_idx = sy * section_cnt + sx

        # -----------------------------------------
        # Radio 정보
        # -----------------------------------------

        radio_freq[rid] = freq
        radio_y[rid] = y
        radio_x[rid] = x

        # -----------------------------------------
        # 모든 주파수 board
        # -----------------------------------------

        board[sec_idx].append(rid)

        # -----------------------------------------
        # 주파수별 board
        #
        # 전체 2차원 배열을 freq마다 만드는 게 아니라
        # 실제 radio가 존재하는 section만 생성
        # -----------------------------------------

        freq_board = specific_board.get(freq)

        if freq_board is None:
            freq_board = {}
            specific_board[freq] = freq_board

        bucket = freq_board.get(sec_idx)

        if bucket is None:
            freq_board[sec_idx] = [rid]
        else:
            bucket.append(rid)


def getMinPower(mID: int, mCount: int) -> int:

    cur_freq = radio_freq[mID]
    cur_y = radio_y[mID]
    cur_x = radio_x[mID]

    cur_sec_y = cur_y // SEC_SIZE
    cur_sec_x = cur_x // SEC_SIZE

    # 해당 주파수 전용 section map
    freq_board = specific_board[cur_freq]

    L = limit_sec

    y_start = max(0, cur_sec_y - L)
    y_end = min(section_cnt - 1, cur_sec_y + L)

    x_start = max(0, cur_sec_x - L)
    x_end = min(section_cnt - 1, cur_sec_x + L)

    # ---------------------------------------------
    # 최대 mCount개만 유지하는 최대힙
    #
    # Python은 min heap이므로
    # (-power, -ID) 저장
    #
    # root = 현재 선택된 후보 중 가장 나쁜 후보
    # ---------------------------------------------

    hq = []

    for sy in range(y_start, y_end + 1):

        sec_dy = abs(sy - cur_sec_y)

        for sx in range(x_start, x_end + 1):

            sec_dx = abs(sx - cur_sec_x)

            sec_idx = sy * section_cnt + sx

            # =====================================
            # 가장 바깥 한 겹
            #
            # 다른 주파수는 +1000 때문에
            # 여기까지 도달할 수 없음.
            #
            # 같은 주파수만 확인한다.
            # =====================================

            if sec_dy == L or sec_dx == L:

                candidates = freq_board.get(sec_idx)

                if candidates is None:
                    continue

                for nxt_id in candidates:

                    if nxt_id == mID:
                        continue

                    dist = (
                        abs(cur_y - radio_y[nxt_id])
                        +
                        abs(cur_x - radio_x[nxt_id])
                    )

                    power = dist * 10

                    # section은 사각형이므로
                    # 실제 Manhattan distance로 마지막 확인
                    if power > g_limit:
                        continue

                    # ---------------------------------
                    # mCount개의 최소 후보만 유지
                    #
                    # 우선순위:
                    # 1. power 작은 것
                    # 2. ID 작은 것
                    # ---------------------------------

                    item = (-power, -nxt_id)

                    if len(hq) < mCount:
                        heapq.heappush(hq, item)

                    elif item > hq[0]:
                        heapq.heapreplace(hq, item)

            # =====================================
            # 안쪽 영역
            #
            # 같은 주파수 / 다른 주파수
            # 모두 연결 가능성이 있으므로
            # 전체 board 확인
            # =====================================

            else:

                for nxt_id in board[sec_idx]:

                    if nxt_id == mID:
                        continue

                    dist = (
                        abs(cur_y - radio_y[nxt_id])
                        +
                        abs(cur_x - radio_x[nxt_id])
                    )

                    if radio_freq[nxt_id] == cur_freq:
                        power = dist * 10
                    else:
                        power = dist * 10 + 1000

                    if power > g_limit:
                        continue

                    item = (-power, -nxt_id)

                    if len(hq) < mCount:
                        heapq.heappush(hq, item)

                    elif item > hq[0]:
                        heapq.heapreplace(hq, item)

    # 문제에서 mCount개 이상 연결 가능함을 보장
    answer = 0

    for neg_power, neg_id in hq:
        answer -= neg_power

    return answer


