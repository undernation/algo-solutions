import heapq
from collections import deque

g_N = -1
graph = []
roads = {}
road_dict = {}
reversed_graph = []
INF = 10 ** 18


class Road:
    def __init__(self):
        self.start = -1
        self.end = -1
        self.is_ok = True
        self.take_time = -1


def init(N, K, mId, sCity, eCity, mTime):
    global graph, g_N, reversed_graph, roads, road_dict
    g_N = N
    graph = [set() for _ in range(N)]

    reversed_graph = [set() for _ in range(N)]

    # key = 경로, value : id
    roads = {}
    road_dict = {}
    for k in range(K):
        road_id = mId[k]
        start_city = sCity[k]
        end_city = eCity[k]
        take_time = mTime[k]

        # 그래프에 추가
        graph[start_city].add(end_city)
        # 역방향 그래프에 추가
        reversed_graph[end_city].add(start_city)

        road = Road()
        road.start = start_city
        road.end = end_city
        road.take_time = take_time
        roads[(start_city, end_city)] = road_id

        road_dict[road_id] = road


def add(mId, sCity, eCity, mTime):
    graph[sCity].add(eCity)
    reversed_graph[eCity].add(sCity)
    roads[(sCity, eCity)] = mId

    road = Road()
    road.start = sCity
    road.end = eCity
    road.take_time = mTime
    roads[(sCity, eCity)] = mId

    road_dict[mId] = road


def remove(mId):
    cur_road = road_dict[mId]

    cur_start = cur_road.start
    cur_end = cur_road.end

    del roads[(cur_start, cur_end)]
    graph[cur_start].remove(cur_end)
    reversed_graph[cur_end].remove(cur_start)

    del road_dict[mId]


def dijkstra(start, end):
    dist = [INF] * g_N
    # print(start)
    dist[start] = 0

    hq = []

    heapq.heappush(hq, (0, start))

    while hq:
        cur_cost, cur_node = heapq.heappop(hq)
        if cur_node == end:
            return cur_cost, dist
        if dist[cur_node] < cur_cost:
            continue

        for nxt_node in graph[cur_node]:
            key = (cur_node, nxt_node)
            cur_road_id = roads[key]
            # print(road_dict)

            if not road_dict[cur_road_id].is_ok:
                continue
            cur_take_time = road_dict[cur_road_id].take_time

            new_cost = cur_cost + cur_take_time

            if new_cost < dist[nxt_node]:
                dist[nxt_node] = new_cost
                heapq.heappush(hq, (new_cost, nxt_node))

    return INF, dist


# 경로 알아내기 용 bfs
def bfs(dist, end):
    visited = set()
    visited.add(end)
    visited_roads = set()
    q = deque()
    q.append(end)

    while q:
        cur_node = q.popleft()
        cur_dist = dist[cur_node]
        for nxt_node in reversed_graph[cur_node]:
            cur_road_id = roads[(nxt_node, cur_node)]
            cur_take_time = road_dict[cur_road_id].take_time
            nxt_dist = dist[nxt_node]
            if nxt_node in visited:
                continue
            if cur_dist - cur_take_time == nxt_dist:
                visited.add(nxt_node)
                visited_roads.add(cur_road_id)
                q.append(nxt_node)

    return visited_roads


def calculate(sCity, eCity):
    # 최단 경로 다익스트라.

    dist, real_dist = dijkstra(sCity, eCity)

    if dist == INF:
        return -1
    min_time = dist

    # route
    visited_roads = bfs(real_dist, eCity)
    max_val = 0
    for visited_road in visited_roads:
        # roads 하나씩 비활성 시키고 최대 시간반환
        road_dict[visited_road].is_ok = False
        new_dist, real_dist = dijkstra(sCity, eCity)
        road_dict[visited_road].is_ok = True

        new_take_time = new_dist
        if new_take_time == INF:
            return -1
        max_val = max(max_val, new_take_time - min_time)

    return max_val


