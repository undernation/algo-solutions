def init() -> None:
    global product_info, matrix, discount_sum, active_count
    discount_sum = [
        [0] * 6
        for _ in range(6)
    ]
    active_count = [
        [0] * 6
        for _ in range(6)
    ]
    # 상품 판매 개수 저장.
    product_info = {}
    # hq 5 x 5 배열.
    matrix = [list([] for col in range(6)) for row in range(6)]

    pass

def sell(mID : int, mCategory : int, mCompany : int, mPrice : int) -> int:
    # 상품 판매 시작
    # 특정 품목, 제조사, 판매 중인 상품 개수 반환.
    stored_price = mPrice + discount_sum[mCategory][mCompany]
    product_info[mID] = [
        mCategory,
        mCompany,
        stored_price,
        True
    ]
    heapq.heappush(matrix[mCategory][mCompany], [stored_price, mID])
    # print("sell", len(matrix[mCategory][mCompany]))
    active_count[mCategory][mCompany] += 1
    return active_count[mCategory][mCompany]

def closeSale(mID : int) -> int:
    if mID not in product_info:
        return -1

    category, company, stored_price, active = product_info[mID]

    if not active:
        return -1

    # 현재 실제 가격
    cur_price = stored_price - discount_sum[category][company]

    product_info[mID][3] = False
    active_count[category][company] -= 1

    return cur_price

def discount(mCategory : int, mCompany : int, mAmount : int) -> int:
    # 특정 범주 상품의 가격 mAmount 만큼 낮춘다.
    # 낮춘게 0이거나 음수되면 해당 상품 판매 종료.
    # 낮춘 후 품목이 mCate 이고 제조사 mcom 판매되는 상품 '개수' 반환
    discount_sum[mCategory][mCompany] += mAmount

    while matrix[mCategory][mCompany]:
        cur_price, cur_id = matrix[mCategory][mCompany][0]
        # closeSale 등으로 이미 죽었던 상품
        if product_info[cur_id][3] == False:
            heapq.heappop(matrix[mCategory][mCompany])
            continue
        if cur_price - discount_sum[mCategory][mCompany] <= 0:
            heapq.heappop(matrix[mCategory][mCompany])
            product_info[cur_id][3] = False
            active_count[mCategory][mCompany] -= 1
        else:
            break

    # print("discount", cnt)
    return active_count[mCategory][mCompany]

def case(mhow, mcode):
    if mhow == 0:
        #모든 상품
        i_start = 1
        i_end = 6
        j_start = 1
        j_end = 6
    elif mhow == 1:
        # mcode 카테고리
        i_start = mcode
        i_end = mcode + 1
        j_start = 1
        j_end = 6
    else:
        # mcode 회사
        i_start = 1
        i_end = 6
        j_start = mcode
        j_end = mcode + 1

    hq = []
    removed = []
    for i in range(i_start, i_end):
        for j in range(j_start, j_end):
            while matrix[i][j]:
                cur_price, cur_id = heapq.heappop(matrix[i][j])
                if product_info[cur_id][3] == False:
                    continue
                heapq.heappush(hq, [cur_price - discount_sum[i][j], cur_id, i, j])
                removed.append([cur_price, cur_id, i, j])
                break
    result = [0] * 5
    # 5개 뽑기
    cnt = 0

    while hq and cnt < 5:
        cur_price, cur_id, i, j = heapq.heappop(hq)

        while matrix[i][j]:
            new_price, new_id = heapq.heappop(matrix[i][j])
            if product_info[new_id][3] == False:
                continue
            heapq.heappush(hq, [new_price - discount_sum[i][j], new_id, i, j])
            removed.append([new_price, new_id, i, j])
            break
        # print("debug hq cur_id cnt", hq, cur_id, cnt)

        result[cnt] = cur_id
        cnt += 1
    # show는 조회일 뿐이므로 정상 상품 복구
    for stored_price, pid, i, j,  in removed:
        heapq.heappush(
            matrix[i][j],
            [stored_price, pid]
        )
    ret = RESULT(cnt, result)
    return ret

def show(mHow : int, mCode : int) -> RESULT:
    # mHow 가 0 인경우 모든 상품에 대해서
    # mhow 가 1인 경우 품목이 mcode 에 대해서
    # mhow 가 2인 경우 제조사 mcode 모든 상품.
    # 가격 낮은순, 같으면 id 적은순
    result = case(mHow, mCode)

    # print("show", result.cnt, result.IDs)
    return result


