import heapq
class RESULT:
    def __init__(self, cnt, IDs):
        self.cnt = cnt
        self.IDs = IDs  # [int] * 5

# 상품 id 로 구분됨.
# 검색시 가격 낮은 순서대로 5개 상품 검색
# 조건 전체 상품
